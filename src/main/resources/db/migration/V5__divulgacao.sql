-- Divulgação: em quais canais cada carro foi publicado (e quando saiu do ar),
-- e de qual canal veio cada interessado.
CREATE TABLE publicacao (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anuncio_id   BIGINT       NOT NULL REFERENCES anuncio (id) ON DELETE CASCADE,
    canal        VARCHAR(20)  NOT NULL,
    link         VARCHAR(500),
    publicada_em DATE         NOT NULL,
    removida_em  DATE,
    CONSTRAINT uk_publicacao UNIQUE (anuncio_id, canal)
);
CREATE INDEX idx_publicacao_anuncio ON publicacao (anuncio_id);

