CREATE TABLE arquivo_importado (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_original         VARCHAR(255) NOT NULL,
    tipo                  VARCHAR(10)  NOT NULL,
    tamanho_bytes         BIGINT       NOT NULL,
    caminho_armazenamento VARCHAR(255) NOT NULL,
    importado_em          TIMESTAMP    NOT NULL
);

CREATE TABLE registro_historico (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operacao     VARCHAR(30)   NOT NULL,
    detalhes     VARCHAR(1000),
    realizado_em TIMESTAMP     NOT NULL
);
CREATE INDEX idx_historico_data ON registro_historico (realizado_em);

CREATE TABLE veiculo (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa      VARCHAR(7)   NOT NULL UNIQUE,
    chassi     VARCHAR(255),
    marca      VARCHAR(255),
    modelo     VARCHAR(255),
    versao     VARCHAR(255),
    ano_modelo VARCHAR(255)
);

CREATE TABLE ficha_tecnica (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    veiculo_id         BIGINT       NOT NULL REFERENCES veiculo (id),
    arquivo_origem_id  BIGINT       REFERENCES arquivo_importado (id),
    status             VARCHAR(20)  NOT NULL,
    fontes_consultadas VARCHAR(1000),
    criada_em          TIMESTAMP    NOT NULL,
    atualizada_em      TIMESTAMP    NOT NULL
);

CREATE TABLE campo_ficha (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ficha_id           BIGINT        NOT NULL REFERENCES ficha_tecnica (id) ON DELETE CASCADE,
    campo              VARCHAR(30)   NOT NULL,
    valor              VARCHAR(2000),
    origem             VARCHAR(20),
    fonte_detalhe      VARCHAR(255),
    status_verificacao VARCHAR(20)   NOT NULL,
    CONSTRAINT uk_campo_ficha UNIQUE (ficha_id, campo)
);
