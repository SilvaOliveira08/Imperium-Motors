-- Loja de veículos: anúncios montados a partir das fichas técnicas concluídas,
-- custos de cada carro, interessados e a venda.

CREATE TABLE anuncio (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ficha_id            BIGINT         NOT NULL REFERENCES ficha_tecnica (id),
    titulo              VARCHAR(120)   NOT NULL,
    preco               NUMERIC(12, 2) NOT NULL,
    valor_compra        NUMERIC(12, 2),
    data_compra         DATE,
    quilometragem       INTEGER        NOT NULL,
    descricao           VARCHAR(4000),
    destaque            BOOLEAN        NOT NULL DEFAULT FALSE,
    status              VARCHAR(20)    NOT NULL,
    comprador_nome      VARCHAR(150),
    comprador_documento VARCHAR(20),
    valor_venda         NUMERIC(12, 2),
    data_venda          DATE,
    forma_pagamento     VARCHAR(30),
    criado_em           TIMESTAMP      NOT NULL,
    atualizado_em       TIMESTAMP      NOT NULL
);
CREATE INDEX idx_anuncio_status ON anuncio (status);

CREATE TABLE anuncio_foto (
    anuncio_id BIGINT      NOT NULL REFERENCES anuncio (id) ON DELETE CASCADE,
    ordem      INTEGER     NOT NULL,
    arquivo    VARCHAR(80) NOT NULL,
    PRIMARY KEY (anuncio_id, ordem)
);

CREATE TABLE despesa (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anuncio_id BIGINT         NOT NULL REFERENCES anuncio (id) ON DELETE CASCADE,
    data       DATE           NOT NULL,
    categoria  VARCHAR(30)    NOT NULL,
    descricao  VARCHAR(255),
    valor      NUMERIC(12, 2) NOT NULL,
    origem     VARCHAR(255)   NOT NULL,
    criada_em  TIMESTAMP      NOT NULL
);
CREATE INDEX idx_despesa_anuncio ON despesa (anuncio_id);

CREATE TABLE proposta (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anuncio_id      BIGINT         NOT NULL REFERENCES anuncio (id) ON DELETE CASCADE,
    tipo            VARCHAR(20)    NOT NULL,
    nome            VARCHAR(150)   NOT NULL,
    telefone        VARCHAR(20),
    email           VARCHAR(150),
    mensagem        VARCHAR(2000),
    valor_oferecido NUMERIC(12, 2),
    data_preferida  DATE,
    status          VARCHAR(20)    NOT NULL,
    criada_em       TIMESTAMP      NOT NULL,
    atualizada_em   TIMESTAMP      NOT NULL
);
CREATE INDEX idx_proposta_status ON proposta (status);
